_parts = []
_mats = {}


def lin(h):
    h = h.lstrip("#")
    out = []
    for i in (0, 2, 4):
        v = int(h[i:i + 2], 16) / 255.0
        out.append(v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4)
    return tuple(out)


def mat(col):
    paint = col.startswith("P")
    h = col[1:] if paint else col
    name = ("paint_" if paint else "c_") + h
    if name not in _mats:
        _mats[name] = c.material(name, lin(h))
    return _mats[name]


def g2b(p):
    return (p[0], -p[2], p[1])


def _link(me, name, col, smooth=False):
    ob = bpy.data.objects.new(name, me)
    bpy.context.scene.collection.objects.link(ob)
    me.materials.append(mat(col))
    for p in me.polygons:
        p.use_smooth = smooth
    _parts.append(ob)
    return ob


def B(size, at, col, bev=0.008, seg=1, rot=None):
    """Box (Godot size and centre), bevelled."""
    me = bpy.data.meshes.new("b")
    bm = bmesh.new()
    bmesh.ops.create_cube(bm, size=1.0)
    for v in bm.verts:
        v.co.x *= size[0]
        v.co.y *= size[2]
        v.co.z *= size[1]
    b = min(bev, min(size) * 0.45)
    if b > 0.0005:
        bmesh.ops.bevel(bm, geom=bm.edges[:], offset=b, segments=seg, affect="EDGES", profile=0.5)
    bm.to_mesh(me)
    bm.free()
    ob = _link(me, "b", col, seg > 1)
    if rot:
        ob.rotation_euler = (math.radians(rot[0]), math.radians(-rot[2]), math.radians(rot[1]))
    ob.location = g2b(at)
    return ob


def C(r, h, at, col, axis="y", seg=16, r2=None, rot=None):
    """Cylinder (or cone with top radius r2) along a Godot axis."""
    me = bpy.data.meshes.new("c")
    bm = bmesh.new()
    bmesh.ops.create_cone(bm, cap_ends=True, segments=seg, radius1=r, radius2=r if r2 is None else r2, depth=h)
    bm.to_mesh(me)
    bm.free()
    ob = _link(me, "c", col, True)
    if rot:
        ob.rotation_euler = (math.radians(rot[0]), math.radians(-rot[2]), math.radians(rot[1]))
    elif axis == "x":
        ob.rotation_euler = (0, math.radians(90), 0)
    elif axis == "z":
        ob.rotation_euler = (math.radians(90), 0, 0)
    ob.location = g2b(at)
    return ob


def S(r, at, col, scale=(1, 1, 1), seg=12):
    me = bpy.data.meshes.new("s")
    bm = bmesh.new()
    bmesh.ops.create_uvsphere(bm, u_segments=seg, v_segments=max(6, seg // 2), radius=r)
    for v in bm.verts:
        v.co.x *= scale[0]
        v.co.y *= scale[2]
        v.co.z *= scale[1]
    bm.to_mesh(me)
    bm.free()
    ob = _link(me, "s", col, True)
    ob.location = g2b(at)
    return ob


def T(R, r, at, col, axis="y", seg=20):
    me = bpy.data.meshes.new("t")
    bm = bmesh.new()
    # A torus from a circle swept round.
    ring = []
    for i in range(seg):
        a = 2 * math.pi * i / seg
        row = []
        for j in range(8):
            b = 2 * math.pi * j / 8
            x = (R + r * math.cos(b)) * math.cos(a)
            y = (R + r * math.cos(b)) * math.sin(a)
            z = r * math.sin(b)
            row.append(bm.verts.new((x, y, z)))
        ring.append(row)
    for i in range(seg):
        for j in range(8):
            a = ring[i][j]
            b = ring[(i + 1) % seg][j]
            cc = ring[(i + 1) % seg][(j + 1) % 8]
            d = ring[i][(j + 1) % 8]
            bm.faces.new((a, b, cc, d))
    bm.to_mesh(me)
    bm.free()
    ob = _link(me, "t", col, True)
    if axis == "z":
        ob.rotation_euler = (math.radians(90), 0, 0)
    elif axis == "x":
        ob.rotation_euler = (0, math.radians(90), 0)
    ob.location = g2b(at)
    return ob


def cushion(size, at, col, rot=None):
    return B(size, at, col, min(0.05, min(size) * 0.35), 2, rot)


def legs4(w, d, h, y0, t, col, inset=0.03, round_=False):
    """Four legs, tops at y0 + h, standing on y0 (w, d: outer spread)."""
    for sx in (-1, 1):
        for sz in (-1, 1):
            x = sx * (w / 2 - inset - t / 2)
            z = sz * (d / 2 - inset - t / 2)
            if round_:
                C(t / 2, h, (x, y0 + h / 2, z), col, seg=8)
            else:
                B((t, h, t), (x, y0 + h / 2, z), col, 0.004)


def handle(at, col="8a8d92", vertical=False, l=0.12):
    if vertical:
        B((0.018, l, 0.022), at, col, 0.006)
    else:
        B((l, 0.018, 0.022), at, col, 0.006)


def books(x0, x1, y, z, depth, rng_seed, cols=("8a2f20", "2f5d8a", "3f6b3a", "c9a23a", "5a2a4a", "d8cba8", "2a2a30")):
    """A row of books standing on a shelf at y, from x0 to x1."""
    x = x0
    k = rng_seed
    while x < x1 - 0.03:
        k = (k * 1103515245 + 12345) & 0x7fffffff
        w = 0.025 + (k % 30) / 1000.0
        h = 0.17 + (k % 70) / 1000.0
        if x + w > x1:
            break
        B((w, h, depth * (0.8 + (k % 20) / 100.0)), (x + w / 2, y + h / 2, z), cols[k % len(cols)], 0.003)
        x += w + 0.002


